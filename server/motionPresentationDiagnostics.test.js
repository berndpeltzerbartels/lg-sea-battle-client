import test from 'node:test';
import assert from 'node:assert/strict';
import { NullEngine } from '@babylonjs/core/Engines/nullEngine.js';
import { Scene } from '@babylonjs/core/scene.js';
import { TransformNode } from '@babylonjs/core/Meshes/transformNode.js';
import { FreeCamera } from '@babylonjs/core/Cameras/freeCamera.js';
import { Vector3 } from '@babylonjs/core/Maths/math.vector.js';
import '@babylonjs/core/Culling/ray.js';
import { createMotionPresentationDiagnostics } from '../src/motionPresentationDiagnostics.js';

test('diagnostics distinguish corrected local coordinates, Babylon world transform and stale camera', () => {
  const engine = new NullEngine();
  const scene = new Scene(engine);
  const parent = new TransformNode('parent', scene);
  parent.position.x = 10;
  const root = new TransformNode('boat', scene);
  root.parent = parent;
  const camera = new FreeCamera('bridge', new Vector3(0, 2, -3), scene);
  scene.activeCamera = camera;
  root.computeWorldMatrix(true);
  scene.render();
  const diagnostics = createMotionPresentationDiagnostics();
  diagnostics.begin({ id: 'ship', x: 100, z: 200, heading: 0 }, root, camera);
  root.position.set(100, 0, 200);
  diagnostics.applied(root, camera);
  root.computeWorldMatrix(true);
  scene.render();
  diagnostics.rendered(root, camera);
  const first = diagnostics.report().latest;
  assert.equal(first.server.x, 100);
  assert.equal(first.applied.local.x, 100);
  assert.equal(first.rendered.world.x, 110, 'parent offset must be visible');
  assert.equal(Math.abs(first.rendered.camera.world.x), 0, 'unmoved camera must not masquerade as corrected');
  assert.equal(first.rendered.camera.view.length, 16);
  diagnostics.begin({ id: 'ship', x: 101, z: 200 }, root, camera);
  assert.equal(diagnostics.report().lastRendered.sequence, first.sequence);
  camera.position.x = 101;
  scene.render();
  diagnostics.rendered(root, camera);
  assert.equal(diagnostics.report().latest.rendered.camera.world.x, 101);
  assert.equal(Math.abs(first.rendered.camera.world.x), 0, 'stored values do not track mutable Babylon vectors');
  scene.dispose();
  engine.dispose();
});
